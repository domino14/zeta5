import sys
sys.path.insert(0,'/home/cesar/code/zeta5/checks')
import io,contextlib
with contextlib.redirect_stdout(io.StringIO()):
    import check_constants as cc
from fractions import Fraction as Fr
from math import floor
pts=cc.ypts
def L(q): return f"({q.numerator} / {q.denominator} : ℝ)" if q.denominator!=1 else f"({q.numerator} : ℝ)"
out=[]
out.append('''import Zeta5.Integrals5Base

/-! # (5.10): the outer integral (generated by gen/gen_outer.py) -/

open MeasureTheory Set Finset
set_option linter.unusedSimpArgs false
set_option linter.deprecated false
noncomputable section
namespace Zeta5
open I5

lemma sum5 (h : ℕ → ℝ) : ∑ j ∈ Finset.Icc (1 : ℕ) 5, h j = h 1 + h 2 + h 3 + h 4 + h 5 := by
  rw [show Finset.Icc (1 : ℕ) 5 = {1, 2, 3, 4, 5} from rfl]; simp [Finset.sum_insert]; ring
''')
names=[]
for i,(a,b) in enumerate(zip(pts,pts[1:])):
    m=(a+b)/2
    samples=[a+(b-a)*Fr(k,8) for k in range(1,8)]
    v=[cc.Tout(s) for s in samples]
    c1=(v[-1]-v[0])/(samples[-1]-samples[0]); c0=v[0]-c1*samples[0]
    assert all(vv==c0+c1*s for s,vv in zip(samples,v))
    K=floor(1/m)
    out.append(f'''
lemma outer_piece_{i} : IntervalIntegrable Lim.outerIntegrand volume {L(a)} {L(b)} ∧
    ∫ y in {L(a)}..{L(b)}, Lim.outerIntegrand y =
      ({L(c0)} * {L(b)} + {L(c1)} * {L(b)} ^ 2 / 2 + 0 * {L(b)} ^ 3 / 3) -
      ({L(c0)} * {L(a)} + {L(c1)} * {L(a)} ^ 2 / 2 + 0 * {L(a)} ^ 3 / 3) := by
  refine piece_quad' (by norm_num) _ _ _ fun y hy => ?_
  obtain ⟨h1, h2⟩ := hy
  simp only [Lim.outerIntegrand, sum5, Nat.cast_ofNat, Nat.cast_one, Lim.R0, Lim.dfun, Lim.pos,
    Lim.α, Lim.lam]
  rw [floor_inv_eq {K} (by norm_num at h1 h2 ⊢; linarith) (by push_cast; nlinarith)
    (by push_cast; nlinarith)]
  simp (disch := dsch) only [if_pos, if_neg, max_eq_left, max_eq_right, min_eq_left, min_eq_right]
  push_cast
  ring
''')
    names.append(f'outer_piece_{i}')
expr=names[0]
for n in names[1:]: expr=f'(chain {expr} {n})'
out.append(f'''
theorem integral_5_10' : ∫ y in (1 / 3 : ℝ)..(2 * Lim.lam), Lim.outerIntegrand y = (Iout : ℝ) := by
  have h := {expr}
  rw [show (2 * Lim.lam : ℝ) = {L(2*cc.lam)} by norm_num [Lim.lam], h.2]
  norm_num [Iout]

end Zeta5
''')
open('Zeta5/Integrals5Outer.lean','w').write(''.join(out))
print(len(names))
