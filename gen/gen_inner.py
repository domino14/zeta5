import sys
sys.path.insert(0,'/home/cesar/code/zeta5/checks')
import io,contextlib
with contextlib.redirect_stdout(io.StringIO()):
    import check_constants as cc
from fractions import Fraction as Fr
from math import floor
al=cc.alpha; lam=cc.lam; H=cc.H
pts=cc.breakpoints(3,20,[Fr(2),2*al,2*lam,2*H,4*al,2*(1-al),2*(1+al)])
def L(q): return f"({q.numerator} / {q.denominator} : ℝ)" if q.denominator!=1 else f"({q.numerator} : ℝ)"
out=['''import Zeta5.Integrals5Gam

/-! # (5.18): `∫₃²⁰ R/x³` (generated by gen/gen_inner.py) -/

open MeasureTheory Set
set_option linter.unusedSimpArgs false
set_option linter.deprecated false
noncomputable section
namespace Zeta5
open I5
''']
names=[]
tot=Fr(0)
for i,(a,b) in enumerate(zip(pts,pts[1:])):
    m=(a+b)/2
    samples=[a+(b-a)*Fr(k,8) for k in range(1,8)]
    v=[cc.R(s) for s in samples]
    A=(v[-1]-v[0])/(samples[-1]-samples[0]); B=v[0]-A*samples[0]
    assert all(vv==A*s+B for s,vv in zip(samples,v)), (a,b)
    tot+=(-A/b-B/(2*b*b))-(-A/a-B/(2*a*a))
    ks=[floor(m),floor(al*m),floor(2*H*m),floor(2*m),floor(2*lam*m)]
    args=["x","(Lim.α * x)","(2 * Lim.Hc * x)","(2 * x)","(2 * (Lim.lam * x))"]
    rws=",\n    ".join(f"fract_nat {u} {k} (by (norm_num [Lim.α, Lim.Hc, Lim.lam]; try linarith))\n      (by (norm_num [Lim.α, Lim.Hc, Lim.lam]; try linarith))" for u,k in zip(args,ks))
    out.append(f'''
lemma inner_piece_{i} : IntervalIntegrable (fun x => Lim.R x / x ^ 3) volume {L(a)} {L(b)} ∧
    ∫ x in {L(a)}..{L(b)}, Lim.R x / x ^ 3 =
      (-{L(A)} / {L(b)} - {L(B)} / (2 * {L(b)} ^ 2)) - (-{L(A)} / {L(a)} - {L(B)} / (2 * {L(a)} ^ 2)) := by
  refine piece_rat' (by norm_num) (by norm_num) _ _ fun x hx => ?_
  obtain ⟨h1, h2⟩ := hx
  rw [R_eq, {rws}]
  simp only [I5.Qc, I5.d0, I5.es, Lim.pos, Lim.α, Lim.Hc, Lim.lam, Nat.cast_ofNat, Nat.cast_zero, Nat.cast_one]
  simp (disch := dsch) only [if_pos, if_neg, max_eq_left, max_eq_right, min_eq_left, min_eq_right]
  ring
''')
    names.append(f'inner_piece_{i}')
assert tot==Fr(322437603634266857629,7535670527041937280000)
# balanced chain
def build(ns):
    if len(ns)==1: return ns[0]
    h=len(ns)//2
    return f'(chain {build(ns[:h])} {build(ns[h:])})'
out.append(f'''
theorem integral_5_18' :
    ∫ x in (3 : ℝ)..20, Lim.R x / x ^ 3 = 322437603634266857629 / 7535670527041937280000 := by
  have h := {build(names)}
  rw [h.2]
  norm_num

theorem R_div_intervalIntegrable_3_20 :
    IntervalIntegrable (fun x => Lim.R x / x ^ 3) volume 3 20 :=
  ({build(names)}).1

end Zeta5
''')
open(sys.argv[1],'w').write(''.join(out))
print(len(names))
